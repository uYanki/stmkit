uint16_t ModbusCRC16(uint8_t* pucFrame, uint16_t usLen)
{
    uint8_t ucCRCHi = 0xFF;
    uint8_t ucCRCLo = 0xFF;
    int     iIndex;

    while (usLen--)
    {
        iIndex  = ucCRCLo ^ *(pucFrame++);
        ucCRCLo = ucCRCHi ^ aucCRCHi[iIndex];
        ucCRCHi = aucCRCLo[iIndex];
    }
    return ucCRCHi << 8 | ucCRCLo;
}

uint8_t be8(uint8_t* ptr)
{
    uint8_t res;

    res = ptr[0];

    return res;
}

uint16_t be16(uint8_t* ptr)
{
    uint16_t res;

    res = ptr[0] << 8;
    res |= ptr[1] << 0;

    return res;
}

uint32_t be32(uint8_t* ptr)
{
    uint32_t res;

    res = ptr[0] << 24;
    res |= ptr[1] << 16;
    res |= ptr[2] << 8;
    res |= ptr[3] << 0;

    return res;
}

