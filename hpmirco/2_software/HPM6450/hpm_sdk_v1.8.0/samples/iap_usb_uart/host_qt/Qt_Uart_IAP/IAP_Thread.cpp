static bool isContainChar(const QByteArray bytes, char ch)
{
    for (int i = 0; i < bytes.size(); ++i)
    {
        if (bytes.at(i) == ch)
        {
            return true;
        }
    }

    return false;
}

IAP_Thread::IAP_Thread(QObject* parent)
    : QThread(parent)
{

}

IAP_Thread::~IAP_Thread()
{
    if (isRunning())
    {
        quit();
        wait(2);
    }
}

bool IAP_Thread::start(const QByteArray& fileData)
{
    //
    // setup data
    //

    if (fileData.isEmpty())
    {
        return false;
    }

    m_TransferData = fileData;
    quint16 checkSum = ModbusCrc16(m_TransferData); // CRC校验
    m_TransferData.append((checkSum >> 8) & 0xFF);
    m_TransferData.append((checkSum >> 0) & 0xFF);

    //
    // connect SerialPort
    //

    SerialPort = new QSerialPort();
    SerialPort->moveToThread(this);

    SerialPort->setPortName(m_UartConfig.port);
    SerialPort->setBaudRate(m_UartConfig.baudrate);
    SerialPort->setDataBits(m_UartConfig.databits);
    SerialPort->setParity(m_UartConfig.parity);
    SerialPort->setStopBits(m_UartConfig.stopbits);
    SerialPort->setFlowControl(QSerialPort::NoFlowControl);
    SerialPort->setReadBufferSize(128);

    SerialPort->open(QIODevice::ReadWrite);

    msleep(20);

    if (SerialPort->isOpen() == false)
    {
        delete SerialPort;
        return false;
    }

    //
    // run iap thread
    //

    connect(this, &QThread::finished, SerialPort, &QSerialPort::deleteLater);
    connect(SerialPort, &QSerialPort::errorOccurred, this, &IAP_Thread::onSerialErrorOccurred, Qt::QueuedConnection);

    QThread::start();

    return true;
}

void IAP_Thread::stop()
{
    QThread::quit();
}

void IAP_Thread::onSerialErrorOccurred(QSerialPort::SerialPortError error)
{
    if(error == QSerialPort::SerialPortError::ResourceError)
    {
        QThread::terminate();
        emit downloadOver(Status::Disconnect);
    }
}

void IAP_Thread::run()
{
    //
    // shake hand
    //

    uint32_t totalSize = m_TransferData.size();

    emit showProgress(0, totalSize);

    bool bMatchedSpecialChar = false;

    while (bMatchedSpecialChar == false)
    {
        SerialPort->write(QByteArray(1, SHAKE_HAND_A));
        SerialPort->waitForBytesWritten(20);
        SerialPort->flush();

        msleep(10);

        // try to read data from serial port
        qApp->processEvents();

        if (SerialPort->bytesAvailable())
        {
            QByteArray rxData = SerialPort->readAll();
            emit       showDeviceMessage(rxData);
            bMatchedSpecialChar = isContainChar(rxData, SHAKE_HAND_B);
        }
    }

    //
    // earse chip
    //

    msleep(10);
    SerialPort->write((QByteArray(1, SEND_FILE_READY_A)));
    SerialPort->waitForBytesWritten(20);
    SerialPort->flush();

    bMatchedSpecialChar = false;

    while (bMatchedSpecialChar == false)
    {
        // try to read data from serial port
        qApp->processEvents();

        if (SerialPort->bytesAvailable())
        {
            QByteArray rxData   = SerialPort->readAll();
            bMatchedSpecialChar = isContainChar(rxData, SEND_FILE_READY_B);
        }
    }

    //
    // send file
    //

    uint32_t remainingSize = totalSize;
    uint32_t currentPos    = 0;

    while (remainingSize > 0)
    {
        QByteArray data;

        if (remainingSize > 128)
        {
            data = m_TransferData.mid(currentPos, 128);
        }
        else
        {
            data = m_TransferData.mid(currentPos, remainingSize);
        }

        SerialPort->write(data);
        SerialPort->waitForBytesWritten(100);
        qApp->processEvents();

        currentPos += data.size();
        remainingSize -= data.size();

        emit showProgress(currentPos, totalSize);
    }

    msleep(10);

    //
    // read result
    //

    bMatchedSpecialChar = false;

    uint16_t timeout = 200; // 200ms * 50 = 10s

    while (bMatchedSpecialChar == false)
    {
        msleep(50);

        // try to read data from serial port
        qApp->processEvents();

        if (SerialPort->bytesAvailable())
        {
            QByteArray rxData = SerialPort->readAll();

            emit showDeviceMessage(rxData);

            for (int i = 0; i < rxData.size(); ++i)
            {
                switch (rxData.at(i))
                {
                    case SEND_FILE_CHECK_SDRAM_ERROR:
                    case SEND_FILE_RCV_ERROR:
                    case SEND_FILE_PROGRAMM_FLASH_ERROR:
                        bMatchedSpecialChar = true;
                        emit downloadOver(Status::Failure);
                        break;
                    case SEND_FILE_OVER_B:
                        bMatchedSpecialChar = true;
                        emit downloadOver(Status::Success);
                        break;
                    default:
                        break;
                }
            }
        }

        if( --timeout == 0)
        {
            // 超时
            emit downloadOver(Status::Timeout);
            break;
        }
    }

    exit();  // stop thread
}
